@router.post(
    "/compliance",
    response_model=StandardResponse[Dict[str, Any]],
    summary="Generate compliance report",
)
async def generate_compliance_report(
    payload: GenerateReportRequest,
    current_user: UserResponse = Depends(get_current_user),
) -> StandardResponse[Dict[str, Any]]:
    """Initiate a compliance report generation."""
    try:
        pool = database_manager.get_pool()
        async with pool.acquire() as conn:
            # Check ownership implicitly by trying to insert if verification is owned
            v_check = await conn.fetchval("SELECT id FROM verifications WHERE id = $1 AND user_id = $2", payload.verification_id, current_user.id)
            if not v_check:
                raise HTTPException(status_code=404, detail="Verification not found or unauthorized")
                
            report_id = await conn.fetchval(
                """INSERT INTO reports (verification_id, user_id, format, report_type, status, metadata) 
                   VALUES ($1, $2, $3, $4, $5, $6::jsonb) RETURNING id""",
                payload.verification_id, current_user.id, payload.format, 'compliance', 'generated', json.dumps({})
            )
            
        return StandardResponse(success=True, data={"report_id": str(report_id), "status": "generated"})
    except HTTPException:
        raise
    except Exception as exc:
        logger.error("Error generating compliance report: %s", exc)
        raise HTTPException(status_code=500, detail="Failed to generate compliance report")

@router.get(
    "/compliance/{report_id}",
    response_model=StandardResponse[Dict[str, Any]],
    summary="Get compliance report data",
)
async def get_compliance_report(
    report_id: uuid.UUID,
    current_user: UserResponse = Depends(get_current_user),
    repo: VerificationRepository = Depends(lambda: verification_repository),
) -> StandardResponse[Dict[str, Any]]:
    """Retrieve full compliance report JSON data."""
    try:
        pool = database_manager.get_pool()
        async with pool.acquire() as conn:
            report_record = await conn.fetchrow(
                "SELECT * FROM reports WHERE id = $1 AND user_id = $2 AND report_type = 'compliance'",
                report_id, current_user.id
            )
            
        if not report_record:
            raise HTTPException(status_code=404, detail="Compliance report not found or unauthorized")
            
        v_record = await repo.get_verification_by_id(report_record["verification_id"])
        
        # Build compliance object
        compliance_data = {
            "Verification": {
                "ID": str(v_record["id"]),
                "timestamp": v_record["created_at"].isoformat()
            },
            "AI_Response": {
                "original_response": v_record.get("claim", "")
            },
            "Claims": v_record.get("evidence", {}).get("claim_results", []),
            "Audit": [] # Would fetch from audit_events
        }
        
        async with pool.acquire() as conn:
            audit_records = await conn.fetch("SELECT stage, status, created_at FROM audit_events WHERE verification_id = $1 ORDER BY created_at ASC", v_record["id"])
            compliance_data["Audit"] = [{"stage": r["stage"], "status": r["status"], "timestamp": r["created_at"].isoformat()} for r in audit_records]
            
        return StandardResponse(success=True, data=compliance_data)
    except HTTPException:
        raise
    except Exception as exc:
        logger.error("Error retrieving compliance report: %s", exc)
        raise HTTPException(status_code=500, detail="Failed to retrieve compliance report")
