logger = logging.getLogger("verifai.api.reports")

router = APIRouter()

class GenerateReportRequest(BaseModel):
    verification_id: uuid.UUID
    format: str  # 'pdf', 'json', 'csv'

@router.post(
    "",
    response_model=StandardResponse[Dict[str, Any]],
    summary="Generate a verification report",
)
async def generate_report(
    payload: GenerateReportRequest,
    current_user: UserResponse = Depends(get_current_user),
    repo: VerificationRepository = Depends(lambda: verification_repository),
) -> StandardResponse[Dict[str, Any]]:
    """Initiate report generation for a specific verification."""
    try:
        # Check ownership
        record = await repo.get_verification_by_id(payload.verification_id)
        if not record or str(record["user_id"]) != str(current_user.id):
            raise HTTPException(status_code=404, detail="Verification not found or unauthorized")
            
        if payload.format not in ['pdf', 'json', 'csv']:
            raise HTTPException(status_code=400, detail="Unsupported format. Use pdf, json, or csv")
            
        pool = database_manager.get_pool()
        async with pool.acquire() as conn:
            report_id = await conn.fetchval(
                """INSERT INTO reports (verification_id, user_id, format, status, metadata) 
                   VALUES ($1, $2, $3, $4, $5::jsonb) RETURNING id""",
                payload.verification_id, current_user.id, payload.format, 'generated', json.dumps({})
            )
            
        return StandardResponse(success=True, data={"report_id": str(report_id), "status": "generated"})
    except HTTPException:
        raise
    except Exception as exc:
        logger.error("Error generating report for user %s: %s", current_user.id, exc)
        raise HTTPException(status_code=500, detail="Failed to generate report")

@router.get(
    "",
    response_model=StandardResponse[List[Dict[str, Any]]],
    summary="List generated reports",
)
async def list_reports(
    current_user: UserResponse = Depends(get_current_user),
) -> StandardResponse[List[Dict[str, Any]]]:
    """List all reports generated by the user."""
    try:
        pool = database_manager.get_pool()
        async with pool.acquire() as conn:
            records = await conn.fetch(
                "SELECT * FROM reports WHERE user_id = $1 ORDER BY created_at DESC",
                current_user.id
            )
            
        results = [dict(r) for r in records]
        # Convert UUIDs and Datetimes to string for JSON serialization
        for r in results:
            r["id"] = str(r["id"])
            r["verification_id"] = str(r["verification_id"])
            r["user_id"] = str(r["user_id"])
            r["metadata"] = json.loads(r["metadata"]) if isinstance(r["metadata"], str) else r["metadata"]
            
        return StandardResponse(success=True, data=results)
    except Exception as exc:
        logger.error("Error listing reports for user %s: %s", current_user.id, exc)
        raise HTTPException(status_code=500, detail="Failed to list reports")

