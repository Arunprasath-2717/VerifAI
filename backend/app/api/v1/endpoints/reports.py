# --- Download Endpoint (Generates file content dynamically) ---

def generate_csv_content(verification_record: dict) -> str:
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["verification_id", "timestamp", "claim_id", "claim", "verdict", "confidence", "decision_basis"])
    
    evidence = verification_record.get("evidence") or {}
    claim_results = evidence.get("claim_results", [])
    
    for c in claim_results:
        writer.writerow([
            str(verification_record["id"]),
            verification_record["created_at"].isoformat(),
            c.get("claim_id"),
            c.get("claim_text"),
            c.get("verdict"),
            c.get("confidence"),
            c.get("reason")
        ])
        
    return output.getvalue()

@router.get(
    "/{report_id}/download",
    summary="Download the generated report file",
)
async def download_report(
    report_id: uuid.UUID,
    current_user: UserResponse = Depends(get_current_user),
    repo: VerificationRepository = Depends(lambda: verification_repository),
) -> Response:
    """Download the actual report file (PDF, JSON, CSV)."""
    try:
        pool = database_manager.get_pool()
        async with pool.acquire() as conn:
            report_record = await conn.fetchrow(
                "SELECT * FROM reports WHERE id = $1 AND user_id = $2",
                report_id, current_user.id
            )
            
        if not report_record:
            raise HTTPException(status_code=404, detail="Report not found")
            
        verification_id = report_record["verification_id"]
        v_record = await repo.get_verification_by_id(verification_id)
        
        if not v_record:
            raise HTTPException(status_code=404, detail="Verification data not found")
            
        fmt = report_record["format"].lower()
        
        if fmt == "json":
            content = json.dumps(v_record, default=str)
            return Response(content=content, media_type="application/json", headers={"Content-Disposition": f"attachment; filename=report_{report_id}.json"})
            
        elif fmt == "csv":
            content = generate_csv_content(v_record)
            return Response(content=content, media_type="text/csv", headers={"Content-Disposition": f"attachment; filename=report_{report_id}.csv"})
            
        elif fmt == "pdf":
            # Very basic text implementation of PDF since we want to be free-tier friendly without heavy dependencies.
            # In a real app we'd use FPDF or similar.
            content = f"VERIFAI VERIFICATION REPORT\n\nVerification ID: {v_record['id']}\nVerdict: {v_record.get('verdict')}\nTrust Score: {v_record.get('trust_score')}\n\nClaims:\n"
            evidence = v_record.get("evidence") or {}
            for c in evidence.get("claim_results", []):
                content += f"- {c.get('claim_text')} ({c.get('verdict')})\n"
                
            return Response(content=content, media_type="text/plain", headers={"Content-Disposition": f"attachment; filename=report_{report_id}.txt"}) # Fallback to txt representation for now
            
        raise HTTPException(status_code=400, detail="Unsupported format")
        
    except HTTPException:
        raise
    except Exception as exc:
        logger.error("Error downloading report %s: %s", report_id, exc)
        raise HTTPException(status_code=500, detail="Failed to download report")

